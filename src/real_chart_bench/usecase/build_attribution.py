"""ATTRIBUTION.md content per dataset subset (design §7.33, §7.88.1).

Pure: given the registry, papers.json rows and a "is this file on disk"
predicate, build the rows and the document text. The script
(scripts/eval/generate_attribution.py) does the reading and writing.

``core`` keeps the exact header and row format it always had
(data/verified_pairs/ATTRIBUTION.md). ``nc`` is a separate document for the
separate directory data/verified_pairs_nc/: it says the figures are for
non-commercial use only, and flags the NC-SA ones, whose share-alike
condition passes on to anything built from them.
"""

from __future__ import annotations

from collections.abc import Callable, Iterable, Mapping
from typing import Any

from real_chart_bench.domain.dataset_subset import DatasetSubset, distribution_dir_name
from real_chart_bench.domain.licensing import normalize_license_id
from real_chart_bench.domain.verified_pairing import VerificationStatus, VerifiedPairing

CORE_HEADER = """# Attribution

**Auto-generated by `scripts/eval/generate_attribution.py` — do not edit by hand.**
Regenerate after any change to `registry.json` (`python scripts/eval/generate_attribution.py`).

Every image or crop committed under `data/verified_pairs/images/` and
`data/verified_pairs/crops/` is a figure (or a manually-derived crop/orientation
correction of a figure) from an open-access paper, redistributed here under the
license recorded below, per its own `license_id` in
[`registry.json`](registry.json) (design §7.30). "Modified" means the committed
file is a crop and/or orientation correction of the original PDF-extracted
image, not the original image verbatim (design §7.21/§7.24/§7.27) — the
underlying data (curve values) is unchanged either way.

| Paper (DOI) | License | Committed file | Modified from original? |
|---|---|---|---|
"""

NC_HEADER = """# Attribution — NC subset (non-commercial use only)

**Auto-generated by `scripts/eval/generate_attribution.py` — do not edit by hand.**
Regenerate after any change to `registry.json` (`python scripts/eval/generate_attribution.py`).

> **Non-commercial use only.** Every image or crop under
> `data/verified_pairs_nc/` comes from a paper published under a Creative
> Commons **NonCommercial** licence (CC BY-NC or CC BY-NC-SA). You may not use
> these figures, or anything derived from them, for commercial purposes. They
> are kept apart from the `core` figures in `data/verified_pairs/` (CC BY /
> CC BY-SA / CC0), which carry no such restriction (design §7.88).
>
> **ShareAlike.** Rows marked "yes" in the last column are CC BY-NC-SA: if you
> remix, transform or build upon them, you must distribute your contributions
> under the same licence as the original.

Each file is redistributed under the license recorded below, per its own
`license_id` in [`../verified_pairs/registry.json`](../verified_pairs/registry.json)
(design §7.30). "Modified" means the committed file is a crop and/or orientation
correction of the original PDF-extracted image, not the original image verbatim —
the underlying data (curve values) is unchanged either way.

| Paper (DOI) | License | Committed file | Modified from original? | ShareAlike? |
|---|---|---|---|---|
"""


def _is_share_alike(license_id: str | None) -> bool:
    return "sa" in normalize_license_id(license_id).split("-")


def attribution_rows(
    registry: Iterable[VerifiedPairing],
    papers_by_id: Mapping[str, Mapping[str, Any]],
    *,
    subset: DatasetSubset,
    file_exists: Callable[[str], bool],
) -> list[str]:
    """One row per committed, still-present file of ``subset``, sorted and
    de-duplicated for a stable diff between regenerations."""
    crops_prefix = f"data/{distribution_dir_name(subset)}/crops/"
    rows = []
    for pairing in registry:
        if pairing.subset is not subset or not pairing.is_licence_admitted:
            continue  # design §7.88.1: only what the licence lets us ship here
        if pairing.status is not VerificationStatus.VERIFIED or not pairing.image_path:
            continue
        if "/" not in pairing.image_path:
            continue  # not committed under data/ -- nothing to attribute yet
        # The file is what gets redistributed, so the list follows the files on
        # disk, not the registry. A figure dropped for a license term has its
        # image deleted (exclude_license_restricted.py); attributing it here
        # would keep claiming we ship it, under the license we recorded before
        # the term changed.
        if not file_exists(pairing.image_path):
            continue
        paper = papers_by_id.get(pairing.paper_id)
        doi = paper["doi"] if paper else "unknown"
        doi_link = f"[{doi}](https://doi.org/{doi})" if paper else doi
        modified = "yes" if pairing.image_path.startswith(crops_prefix) else "no"
        row = (
            f"| {doi_link} | {pairing.license_id or 'unknown'} "
            f"| `{pairing.image_path}` | {modified} |"
        )
        if subset is DatasetSubset.NC:
            row += f" {'yes' if _is_share_alike(pairing.license_id) else 'no'} |"
        rows.append(row)
    return sorted(set(rows))


def render_attribution(subset: DatasetSubset, rows: list[str]) -> str:
    header = CORE_HEADER if subset is DatasetSubset.CORE else NC_HEADER
    return header + "\n".join(rows) + "\n"
