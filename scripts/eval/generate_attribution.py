"""Generates data/verified_pairs/ATTRIBUTION.md from registry.json + papers.json
(design §7.33, HQ priority-interrupt 2026-08-23).

Why this exists: committing figure images/crops under data/verified_pairs/
(images/, crops/) is active redistribution of copyrighted figure content.
CC BY 4.0 requires attribution (credit the source, indicate the license,
indicate if changes were made) for each redistributed work. Generating this
from the registry rather than hand-writing it means it can never go stale as
the registry grows -- the same "never hardcode what you can derive" lesson
as dataset_version (design §7.28) and the leaderboard version banner.

Usage:
    python scripts/eval/generate_attribution.py
"""

from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / "src"))

from real_chart_bench.adapter.verified_pairing_registry import load_registry  # noqa: E402

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
REGISTRY_PATH = REPO_ROOT / "data/verified_pairs/registry.json"
PAPERS_PATH = REPO_ROOT / "data/manifest/v0/papers.json"
OUT_PATH = REPO_ROOT / "data/verified_pairs/ATTRIBUTION.md"

_HEADER = """# Attribution

**Auto-generated by `scripts/eval/generate_attribution.py` — do not edit by hand.**
Regenerate after any change to `registry.json` (`python scripts/eval/generate_attribution.py`).

Every image or crop committed under `data/verified_pairs/images/` and
`data/verified_pairs/crops/` is a figure (or a manually-derived crop/orientation
correction of a figure) from an open-access paper, redistributed here under the
license recorded below, per its own `license_id` in
[`registry.json`](registry.json) (design §7.30). "Modified" means the committed
file is a crop and/or orientation correction of the original PDF-extracted
image, not the original image verbatim (design §7.21/§7.24/§7.27) — the
underlying data (curve values) is unchanged either way.

| Paper (DOI) | License | Committed file | Modified from original? |
|---|---|---|---|
"""


def main() -> None:
    registry = load_registry(REGISTRY_PATH)
    papers_by_id = {p["paper_id"]: p for p in json.loads(PAPERS_PATH.read_text())}

    rows = []
    for pairing in registry:
        if pairing.status.value != "verified" or not pairing.image_path:
            continue
        if "/" not in pairing.image_path:
            continue  # not committed under data/verified_pairs/ -- nothing to attribute yet
        paper = papers_by_id.get(pairing.paper_id)
        doi = paper["doi"] if paper else "unknown"
        doi_link = f"[{doi}](https://doi.org/{doi})" if paper else doi
        modified = "yes" if pairing.image_path.startswith("data/verified_pairs/crops/") else "no"
        rows.append(
            f"| {doi_link} | {pairing.license_id or 'unknown'} "
            f"| `{pairing.image_path}` | {modified} |"
        )

    # One row per committed file, sorted for a stable diff between regenerations.
    rows = sorted(set(rows))

    OUT_PATH.write_text(_HEADER + "\n".join(rows) + "\n")
    print(f"wrote {OUT_PATH} ({len(rows)} attributed file(s))")


if __name__ == "__main__":
    main()
