"""Materials-science-style synthetic marker charts -> labels.jsonl
(docs/design/local-model.md, データ: 合成).

Fills what PlotQA dot_line lacks: numeric x (T = 300-900 K, 1000/T,
composition, log x), log y and log10-printed y, open/filled markers of
several shapes, error bars, 1-8 series, legends inside the plot, dense and
overlapping markers, line+marker, occasional insets, varied fonts/sizes/dpi,
and JPEG artefacts.

Every marker centre is reported from matplotlib itself: data -> display
through ax.transData after the figure is drawn, then display -> image pixels.
The figure is drawn SS times larger and shrunk, because Agg puts markers on
the integer pixel grid; the shrunk marker sits within ~0.2 px of its label
(tests/scripts/test_gen_synth_materials.py measures the ink centroids).
Tick (px, value) pairs come from the drawn major ticks, the value parsed
from the printed label text. Points hidden under an opaque legend or an
inset are dropped from the label (they are not visible). Insets carry
lines only, never markers, so every visible marker is labelled.

Each image i is drawn from numpy's default_rng(SEED + i): any image can be
regenerated alone. Images are written by a process pool, labels gathered in
order. Data are generated (no real figures, no model outputs).

Usage:
  .venv/bin/python scripts/train/gen_synth_materials.py --n 20000 [--out DIR] [--workers 24]
"""

